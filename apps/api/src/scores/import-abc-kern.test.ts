import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ToneMidi from "@tonejs/midi";
import { describe, expect, it } from "vitest";
import { extractSongMetadata } from "../midi-metadata.js";
import { normalizeAbcChords } from "./abc-chords.js";
import { importScore } from "./import-score.js";
import { decodeScoreFile, MAX_SCORE_TEXT_BYTES } from "./score-file.js";

const { Midi } = ToneMidi;

/**
 * ABC and Humdrum **kern imports. The fixtures (CC0, see fixtures/README.md) have an
 * `.expected.json` beside them: every note as music21 reads it, a reader independent of
 * Verovio (generated by fixtures/expected_notes.py). The played MIDI must match it note
 * for note, as the MusicXML tests do against reference-notes.ts.
 */
const FIXTURES = path.join(path.dirname(fileURLToPath(import.meta.url)), "fixtures");
const fixture = (name: string): Uint8Array => new Uint8Array(readFileSync(path.join(FIXTURES, name)));
const text = (value: string): Uint8Array => new TextEncoder().encode(value);

interface ExpectedNote {
  staff: number;
  midi: number;
  onsetQ: number;
  durationQ: number;
}
const expectedNotes = (name: string): ExpectedNote[] => JSON.parse(readFileSync(path.join(FIXTURES, `${name}.expected.json`), "utf8")).notes;

function played(bytes: Uint8Array) {
  const midi = new Midi(bytes);
  const ppq = midi.header.ppq;
  const notes = midi.tracks.flatMap((track, index) =>
    track.notes.map((note) => ({ staff: index, midi: note.midi, onsetQ: note.ticks / ppq, durationQ: note.durationTicks / ppq })),
  );
  return { notes, midi };
}

const TICK = 1 / 120;

/** Every expected note is played on its staff at its onset and length (a tick of release aside), and nothing else is. */
function expectSameNotes(expected: ExpectedNote[], actual: ExpectedNote[]) {
  const pool = [...actual];
  const missing: ExpectedNote[] = [];
  for (const note of expected) {
    const index = pool.findIndex((candidate) => candidate.staff === note.staff && candidate.midi === note.midi && Math.abs(candidate.onsetQ - note.onsetQ) <= TICK);
    if (index < 0) {
      missing.push(note);
      continue;
    }
    expect(Math.abs(pool[index].durationQ - note.durationQ), JSON.stringify(note)).toBeLessThanOrEqual(TICK + 1e-9);
    pool.splice(index, 1);
  }
  expect({ missing, extra: pool }).toEqual({ missing: [], extra: [] });
}

const signatures = (midi: InstanceType<typeof Midi>) => midi.header.timeSignatures.map((ts) => [ts.ticks / midi.header.ppq, ...ts.timeSignature]);

describe("ABC import", () => {
  it("reads a one-voice tune note for note, with its title and composer (Ode to Joy)", async () => {
    const result = await importScore(fixture("abc-ode-to-joy-melody.abc"));
    expect(result).toMatchObject({ kind: "abc", title: "Ode to Joy", composer: "Ludwig van Beethoven" });
    expect(result.mei).toContain("<mei");
    expect(result.report).toMatchObject({ printedMeasures: 8, playedMeasures: 8, repeatsVerified: null, playedStaves: [0], staffCount: 1, warnings: [] });
    const { notes } = played(result.midi);
    expect(notes).toHaveLength(30);
    expectSameNotes(expectedNotes("abc-ode-to-joy-melody.abc"), notes);
    // One staff is not two hands.
    expect(extractSongMetadata(result.midi).noteCount).toBe(30);
  });

  it("keeps pickup, ties, triplets, chords, a key change, a meter change and carried accidentals (edge cases)", async () => {
    const result = await importScore(fixture("abc-edge-cases.abc"));
    expect(result.report.printedMeasures).toBe(9);
    const expected = expectedNotes("abc-edge-cases.abc");
    const { notes, midi } = played(result.midi);
    expect(notes).toHaveLength(30);
    expectSameNotes(expected, notes);
    // Chord with its length after the bracket: three notes, two beats each.
    expect(notes.filter((note) => Math.abs(note.onsetQ - 7) < TICK).map((note) => [note.midi, Math.round(note.durationQ)])).toEqual([
      [67, 2],
      [71, 2],
      [74, 2],
    ]);
    // The tie across the barline is one note of four beats; the triplet is three thirds of a beat.
    expect(notes.some((note) => note.midi === 76 && Math.abs(note.durationQ - 4) <= TICK + 1e-9)).toBe(true);
    expect(notes.filter((note) => note.onsetQ >= 24 && note.onsetQ < 25).length).toBe(3);
    // A one-beat pickup, 4/4 bars, then 3/4 from the sixth bar after it (1 + 5 x 4 quarter notes): the barlines fall where the score's do.
    expect(signatures(midi)).toEqual([
      [0, 1, 4],
      [1, 4, 4],
      [21, 3, 4],
    ]);
    // 90 quarter notes a minute, as written.
    expect(Math.round(midi.header.tempos[0].bpm)).toBe(90);
  });

  it("is not confused by the key of the tune imported before it", async () => {
    // Verovio's ABC reader keeps the last key's sharps for a later tune in C: each import gets its own module.
    const key = async (k: string) => played((await importScore(text(`X:1\nM:4/4\nL:1/4\nK:${k}\nC D E F|]\n`))).midi).notes.map((note) => note.midi);
    expect(await key("D")).toEqual([61, 62, 64, 66]);
    expect(await key("C")).toEqual([60, 62, 64, 65]);
    expect(await key("Am")).toEqual([60, 62, 64, 65]);
  });

  it("refuses several voices and several tunes, which it would otherwise play wrongly", async () => {
    await expect(importScore(fixture("abc-ode-to-joy-two-voices.abc"))).rejects.toThrow(/2 voices \(RH, LH\)/);
    await expect(importScore(fixture("abc-two-tunes.abc"))).rejects.toThrow("This ABC file holds 2 tunes: upload one tune per file");
    await expect(importScore(text("X:1\nM:4/4\nK:C\nC D E F & E F G A|]\n"))).rejects.toThrow(/overlays voices/);
  });
});

describe("**kern import", () => {
  it("plays a two-spine piano piece as right and left hand, with the key signature (Ode to Joy)", async () => {
    const result = await importScore(fixture("kern-ode-to-joy-piano.krn"));
    expect(result).toMatchObject({ kind: "krn", title: "Ode to Joy (two-hand setting)", composer: "Ludwig van Beethoven" });
    // Both staves are played (the song is saved as "both hands": playedStaves.length >= 2).
    expect(result.report).toMatchObject({ printedMeasures: 8, playedMeasures: 8, repeatsVerified: null, playedStaves: [0, 1], staffCount: 2, warnings: [] });
    const { notes, midi } = played(result.midi);
    expect(notes).toHaveLength(57);
    expectSameNotes(expectedNotes("kern-ode-to-joy-piano.krn"), notes);
    // Track 0 is the top staff and track 1 the bottom one: the play-along parser takes the lower track as the left hand.
    const mean = (staff: number) => {
      const pitches = notes.filter((note) => note.staff === staff).map((note) => note.midi);
      return pitches.reduce((sum, pitch) => sum + pitch, 0) / pitches.length;
    };
    expect(mean(1)).toBeLessThan(mean(0));
    expect(signatures(midi)).toEqual([[0, 4, 4]]);
    // Long enough for the upload pipeline (20 s or more), at the 90 quarter notes a minute written in the file.
    expect(extractSongMetadata(result.midi)).toMatchObject({ noteCount: 57 });
    expect(midi.duration).toBeCloseTo((32 * 60) / 90, 1);
  });

  it("keeps pickup, ties, triplets, chords, a key change and a meter change (edge cases)", async () => {
    const result = await importScore(fixture("kern-edge-cases.krn"));
    expect(result.report).toMatchObject({ printedMeasures: 7, playedStaves: [0, 1], warnings: [] });
    const { notes, midi } = played(result.midi);
    expect(notes).toHaveLength(31);
    expectSameNotes(expectedNotes("kern-edge-cases.krn"), notes);
    // A one-beat pickup, three 4/4 bars (13 quarter notes), then 3/4.
    expect(signatures(midi)).toEqual([
      [0, 1, 4],
      [1, 4, 4],
      [13, 3, 4],
    ]);
    // The dotted-half tie from bar 5 into bar 6 is one six-beat note.
    expect(notes.some((note) => note.midi === 62 && Math.abs(note.durationQ - 6) <= TICK + 1e-9)).toBe(true);
  });

  it("plays every spine of a four-part score (chorale)", async () => {
    const result = await importScore(fixture("kern-chorale-satb.krn"));
    expect(result.report).toMatchObject({ staffCount: 4, playedStaves: [0, 1, 2, 3], warnings: [] });
    const { notes } = played(result.midi);
    expect(notes).toHaveLength(43);
    expectSameNotes(expectedNotes("kern-chorale-satb.krn"), notes);
  });

  it("sounds the spelled accidental of every note, in or out of the key signature", async () => {
    const kern = async (body: string) => played((await importScore(text(`**kern\n*clefG2\n${body}\n=\n*-\n`))).midi).notes.map((note) => note.midi);
    // Verovio writes no accidental for a note that repeats one, or that the key signature already holds.
    expect(await kern("*M4/4\n=1\n4f#\n4f#\n4F#\n4f\n=2\n4f\n4f#\n4ff#\n4f")).toEqual([66, 66, 54, 65, 65, 66, 78, 65]);
    expect(await kern("*k[b-e-]\n*M4/4\n=1\n4b-\n4e-\n4b\n4e\n4B-\n4e-\n4cc#\n4b-")).toEqual([70, 63, 71, 64, 58, 63, 73, 70]);
    expect(await kern("*k[f#]\n*M4/4\n=1\n4f#\n4g\n4f\n4f#")).toEqual([66, 67, 65, 66]);
  });

  it("carries an ABC accidental to the rest of its bar, for the same pitch only", async () => {
    const abc = async (body: string) => played((await importScore(text(`X:1\nM:4/4\nL:1/4\nK:C\n${body}\n`))).midi).notes.map((note) => note.midi);
    expect(await abc("^F F f F|F ^F =F F|]")).toEqual([66, 66, 77, 66, 65, 66, 65, 65]);
  });

  it("refuses a file with two movements", async () => {
    await expect(importScore(fixture("kern-two-movements.krn"))).rejects.toThrow("This Humdrum file holds 2 movements: upload one movement per file");
  });
});

describe("what ABC and **kern files are taken for", () => {
  const ABC = "X:1\nT:t\nM:4/4\nL:1/4\nK:C\nC D E F|]\n";
  const KERN = "**kern\n*clefG2\n=1\n4c\n4d\n=\n*-\n";

  it("reads ABC by its X: and K: lines, past comments, blank lines, a byte-order mark and CRLF", () => {
    expect(decodeScoreFile(text(ABC))).toMatchObject({ kind: "abc", format: "abc" });
    expect(decodeScoreFile(text(`﻿%abc-2.1\n\n% a comment\n${ABC}`))).toMatchObject({ kind: "abc" });
    expect(decodeScoreFile(text(ABC.replace(/\n/g, "\r\n")))).toMatchObject({ kind: "abc" });
    expect(decodeScoreFile(text("X: 12 % reference\nK:G\nG|]\n"))).toMatchObject({ kind: "abc" });
  });

  it("reads kern by its **kern header, past ! comments and with other spines beside it", () => {
    expect(decodeScoreFile(text(KERN))).toMatchObject({ kind: "krn", format: "humdrum" });
    expect(decodeScoreFile(text(`!!!COM: x\n!! comment\n\n**dynam\t**kern\n*\t*clefG2\n=1\t=1\n.\t4c\n*-\t*-\n`))).toMatchObject({ kind: "krn" });
    expect(decodeScoreFile(text(KERN.replace(/\n/g, "\r\n")))).toMatchObject({ kind: "krn" });
  });

  it("refuses ABC that is missing its X: or K: line, or has them out of place", () => {
    expect(() => decodeScoreFile(text("T:no reference\nK:C\nC|]\n"))).toThrow("This isn't a MusicXML, MEI, ABC or **kern score");
    expect(() => decodeScoreFile(text("M:4/4\nX:1\nK:C\nC|]\n"))).toThrow("This isn't a MusicXML, MEI, ABC or **kern score");
    expect(() => decodeScoreFile(text("X:1\nT:t\nM:4/4\n\nK:C\nC|]\n"))).toThrow(/no K: \(key\) line/);
    expect(() => decodeScoreFile(text("X:1\nT:t\nC D E F|]\n"))).toThrow(/no K: \(key\) line/);
    expect(() => decodeScoreFile(text("X:one\nK:C\nC|]\n"))).toThrow("This isn't a MusicXML, MEI, ABC or **kern score");
  });

  it("refuses kern that has no **kern spine, or does not start with one", () => {
    expect(() => decodeScoreFile(text("**dynam\n=1\nf\n*-\n"))).toThrow(/no \*\*kern spine/);
    expect(() => decodeScoreFile(text("**kernel\n4c\n*-\n"))).toThrow(/no \*\*kern spine/);
    expect(() => decodeScoreFile(text("4c\t4d\n*-\n"))).toThrow("This isn't a MusicXML, MEI, ABC or **kern score");
    expect(() => decodeScoreFile(text("!!!COM: x\nsome notes\n**kern\n4c\n*-\n"))).toThrow("This isn't a MusicXML, MEI, ABC or **kern score");
  });

  it("refuses XML, binary and plain text, whatever it is named", () => {
    expect(() => decodeScoreFile(text(`<?xml version="1.0"?><svg>${ABC}</svg>`))).toThrow("This isn't a MusicXML, MEI, ABC or **kern score");
    expect(() => decodeScoreFile(text(`<html>${KERN}</html>`))).toThrow("This isn't a MusicXML, MEI, ABC or **kern score");
    // ABC and kern text with a NUL or other control byte in it.
    expect(() => decodeScoreFile(text(`${ABC}\u0000`))).toThrow("This isn't a MusicXML, MEI, ABC or **kern score");
    expect(() => decodeScoreFile(text(`${KERN}\u0001`))).toThrow("This isn't a MusicXML, MEI, ABC or **kern score");
    expect(() => decodeScoreFile(new Uint8Array([0x58, 0x3a, 0x31, 0x0a, 0xff, 0xfe, 0x4b, 0x3a, 0x43]))).toThrow("This isn't a MusicXML, MEI, ABC or **kern score");
    expect(() => decodeScoreFile(text("hello, this is just a note\n"))).toThrow("This isn't a MusicXML, MEI, ABC or **kern score");
    expect(() => decodeScoreFile(new Uint8Array([0x4d, 0x54, 0x68, 0x64, 0, 0, 0, 6]))).toThrow("This isn't a MusicXML, MEI, ABC or **kern score");
  });

  it("refuses a second tune, a second movement, and extra voices before Verovio sees them", () => {
    expect(() => decodeScoreFile(text(`${ABC}\nX:2\nK:G\nG|]\n`))).toThrow("holds 2 tunes");
    expect(() => decodeScoreFile(text(`${KERN}${KERN}`))).toThrow("holds 2 movements");
    expect(() => decodeScoreFile(text("X:1\nK:C\nV:1\nC|]\nV:2\nE|]\n"))).toThrow(/2 voices/);
    expect(() => decodeScoreFile(text("X:1\nK:C\nV:1\n[V:1] C|] [V:2] E|]\n"))).toThrow(/2 voices/);
    // One named voice is fine, and so is an & inside a quoted chord symbol or lyrics.
    expect(decodeScoreFile(text('X:1\nK:C\nV:1\n"A&B" C|]\nw: you & me\n')).kind).toBe("abc");
  });

  it("keeps the 20 MB cap on the text", () => {
    const big = (head: string) => text(head + " ".repeat(MAX_SCORE_TEXT_BYTES));
    expect(() => decodeScoreFile(big(ABC))).toThrow("The score is larger than 20 MB");
    expect(() => decodeScoreFile(big(KERN))).toThrow("The score is larger than 20 MB");
  });
});

describe("normalizeAbcChords", () => {
  it("multiplies a length written after the bracket into the chord's notes", () => {
    expect(normalizeAbcChords("[CEG]2 [C2E2G2]2 [^C,E'g]3/2 [CE]/2 [CE]/ [CEG]4-")).toBe("[C2E2G2] [C4E4G4] [^C,3/2E'3/2g3/2] [C/2E/2] [C/2E/2] [C4-E4-G4-]");
  });

  it("leaves inline fields, field lines, comments and unrecognised chords alone", () => {
    const abc = "K:D\n[K:G] [M:3/4] [CEG] [C E G]2 [!trill!CE]2\n% [CE]2\nw: [CE]2\n";
    expect(normalizeAbcChords(abc)).toBe(abc);
  });
});
